// Smart helper to filter mock jobs on client side
export function filterClientJobs(jobs, { keyword, experience, location }) {
  if (!Array.isArray(jobs) || jobs.length === 0) return [];

  // Pass 1: Strict matching with all filters
  const pass1 = jobs.filter((job) => {
    let matchesKeyword = true;
    let matchesExp = true;
    let matchesLoc = true;

    if (keyword && keyword.trim()) {
      const q = keyword.trim().toLowerCase();
      const searchable = (
        (job.title || '') + ' ' +
        (job.company || '') + ' ' +
        (Array.isArray(job.skills) ? job.skills.join(' ') : '') + ' ' +
        (job.description || '')
      ).toLowerCase();

      if (searchable.includes(q)) {
        matchesKeyword = true;
      } else {
        const tokens = q.split(/\s+/).filter((w) => w.length > 2 && w !== 'developer' && w !== 'engineer');
        if (tokens.length > 0) {
          matchesKeyword = tokens.some((t) => searchable.includes(t));
        } else {
          matchesKeyword = searchable.includes('developer') || searchable.includes('engineer');
        }
      }
    }

    if (experience !== undefined && experience !== null && experience !== "") {
      const expNum = parseInt(experience, 10);
      if (!isNaN(expNum)) {
        if (expNum >= 6) {
          matchesExp = (job.maxExperience || 5) >= 5 || (job.minExperience || 0) >= 4;
        } else if (expNum === 0) {
          // Freshers match any job open to 0-2 yrs
          matchesExp = (job.minExperience || 0) <= 2;
        } else {
          matchesExp = expNum >= (job.minExperience || 0) && expNum <= (job.maxExperience || 5) + 1;
        }
      }
    }

    if (location && location.trim()) {
      const locClean = location.trim().toLowerCase();
      const jobLoc = (job.location || '').toLowerCase();
      matchesLoc =
        jobLoc.includes(locClean) ||
        (locClean.includes('benga') && (jobLoc.includes('benga') || jobLoc.includes('bangalore'))) ||
        (locClean.includes('noida') && jobLoc.includes('noida')) ||
        (locClean.includes('delhi') && (jobLoc.includes('delhi') || jobLoc.includes('gurugram') || jobLoc.includes('noida'))) ||
        jobLoc.includes('remote');
    }

    return matchesKeyword && matchesExp && matchesLoc;
  });

  if (pass1.length > 0) return pass1;

  // Pass 2: Relax experience if strict gave 0
  if (keyword || location) {
    const pass2 = jobs.filter((job) => {
      let matchesKeyword = true;
      let matchesLoc = true;
      if (keyword && keyword.trim()) {
        const q = keyword.trim().toLowerCase();
        const searchable = ((job.title || '') + ' ' + (job.company || '') + ' ' + (Array.isArray(job.skills) ? job.skills.join(' ') : '') + ' ' + (job.description || '')).toLowerCase();
        if (searchable.includes(q)) {
          matchesKeyword = true;
        } else {
          const tokens = q.split(/\s+/).filter((w) => w.length > 2 && w !== 'developer' && w !== 'engineer');
          matchesKeyword = tokens.length > 0 ? tokens.some((t) => searchable.includes(t)) : (searchable.includes('developer') || searchable.includes('engineer'));
        }
      }
      if (location && location.trim()) {
        const locClean = location.trim().toLowerCase();
        const jobLoc = (job.location || '').toLowerCase();
        matchesLoc = jobLoc.includes(locClean) || (locClean.includes('benga') && jobLoc.includes('benga')) || (locClean.includes('noida') && jobLoc.includes('noida')) || jobLoc.includes('remote');
      }
      return matchesKeyword && matchesLoc;
    });
    if (pass2.length > 0) return pass2;
  }

  // Pass 3: Match keyword alone
  if (keyword && keyword.trim()) {
    const q = keyword.trim().toLowerCase();
    const pass3 = jobs.filter((job) => {
      const searchable = ((job.title || '') + ' ' + (job.company || '') + ' ' + (Array.isArray(job.skills) ? job.skills.join(' ') : '')).toLowerCase();
      const tokens = q.split(/\s+/).filter((w) => w.length > 2 && w !== 'developer' && w !== 'engineer');
      return searchable.includes(q) || (tokens.length > 0 && tokens.some((t) => searchable.includes(t)));
    });
    if (pass3.length > 0) return pass3;
  }

  // Final fallback: all jobs
  return jobs;
}
